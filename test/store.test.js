import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createStore } from '../lib/store.js';

test('storage accepts the credentials generated by the Vercel Upstash connection', async (t) => {
  const names = [
    'UPSTASH_REDIS_REST_URL', 'UPSTASH_REDIS_REST_TOKEN',
    'UPSTASH_KV_REST_API_URL', 'UPSTASH_KV_REST_API_TOKEN', 'GUARDIAN_STATE_KEY',
  ];
  const previous = Object.fromEntries(names.map((name) => [name, process.env[name]]));
  for (const name of names) delete process.env[name];
  process.env.UPSTASH_KV_REST_API_URL = 'https://redis.test';
  process.env.UPSTASH_KV_REST_API_TOKEN = 'test-integration-token';
  t.after(() => {
    for (const [name, value] of Object.entries(previous)) {
      if (value === undefined) delete process.env[name];
      else process.env[name] = value;
    }
  });
  t.mock.method(globalThis, 'fetch', async (url, init) => {
    assert.equal(url, 'https://redis.test');
    assert.equal(init.headers.authorization, 'Bearer test-integration-token');
    assert.deepEqual(JSON.parse(init.body), ['GET', 'guardian:{monitor}:v1']);
    return Response.json({ result: null });
  });
  assert.equal(await createStore().read(), null);
});
